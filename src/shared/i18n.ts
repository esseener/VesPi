const CATALOG: Record<AppLanguage, Record<keyof typeof ZH, string>> = { zh: ZH, en: EN }

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === 'zh' || value === 'en'
}

export function t(
  language: AppLanguage | null | undefined,
  key: keyof typeof ZH,
  vars?: Record<string, string>,
): string {
  const lang = isAppLanguage(language) ? language : DEFAULT_LANGUAGE
  let out = CATALOG[lang][key] ?? CATALOG[DEFAULT_LANGUAGE][key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, value)
    }
  }
  return out
}

export type MessageKey = keyof typeof ZH

export function isMessageKey(value: string): value is MessageKey {
  return value in ZH
}
